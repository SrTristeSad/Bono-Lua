-- Conformance tests for the original DragonBonesJS BoundingBoxData.ts.
-- Reference: DragonBones/DragonBonesJS@64b6c69ae35777c2404be68c9192e2c56906079e
package.path="./?.lua;./?/init.lua;"..package.path
local Base=require("dragonbones.original.core.BaseObject")
local Core=require("dragonbones.original.core.DragonBones")
local M=require("dragonbones.original.model.BoundingBoxData")
local Rect,Ellipse,Polygon=M.RectangleBoundingBoxData,M.EllipseBoundingBoxData,M.PolygonBoundingBoxData
local passed,failed=0,0
local function test(name,fn)
  local ok,err=pcall(fn)
  if ok then passed=passed+1;print("ok original.boundingbox "..name)
  else failed=failed+1;print("not ok original.boundingbox "..name..": "..tostring(err))
  end
end
local function eq(a,b)
  assert(a==b,tostring(a).." ~= "..tostring(b))
end
local function close(a,b)
  assert(type(a)=="number" and type(b)=="number" and math.abs(a-b)<1e-4,
    tostring(a).." ~= "..tostring(b))
end
local function point() return {} end
local function rectangle()
  local r=Base.borrowObject(Rect)
  r.width=10;r.height=8
  return r
end
local function ellipse()
  local e=Base.borrowObject(Ellipse)
  e.width=10;e.height=6
  return e
end
local function polygon()
  local p=Base.borrowObject(Polygon)
  p.x=0;p.y=0;p.width=10;p.height=10
  p.vertices[1]=0;p.vertices[2]=0
  p.vertices[3]=10;p.vertices[4]=0
  p.vertices[5]=10;p.vertices[6]=10
  p.vertices[7]=0;p.vertices[8]=10
  return p
end

test("original four classes and static toString identifiers",function()
  assert(type(M.BoundingBoxData)=="table")
  eq(Rect.toString(),"[class dragonBones.RectangleBoundingBoxData]")
  -- Upstream class identifier intentionally calls it EllipseData.
  eq(Ellipse.toString(),"[class dragonBones.EllipseData]")
  eq(Polygon.toString(),"[class dragonBones.PolygonBoundingBoxData]")
end)
test("constructor and BaseObject clear initialize original type enum",function()
  local r,e,p=Base.borrowObject(Rect),Base.borrowObject(Ellipse),Base.borrowObject(Polygon)
  eq(r.type,Core.BoundingBoxType.Rectangle)
  eq(e.type,Core.BoundingBoxType.Ellipse)
  eq(p.type,Core.BoundingBoxType.Polygon)
  for _,b in ipairs({r,e,p}) do
    eq(b.color,0);eq(b.width,0);eq(b.height,0)
    b:returnToPool()
  end
end)
test("rectangle containsPoint includes edges and corners as source",function()
  local r=rectangle()
  assert(r:containsPoint(0,0))
  assert(r:containsPoint(-5,-4))
  assert(r:containsPoint(5,4))
  assert(not r:containsPoint(5.01,0))
  assert(not r:containsPoint(0,-4.1))
  r:returnToPool()
end)
test("rectangle inside-to-inside segment returns -1",function()
  local r=rectangle()
  eq(r:intersectsSegment(-1,0,1,1),-1)
  r:returnToPool()
end)
test("rectangle outside-to-outside non intersecting returns 0",function()
  local r=rectangle()
  eq(r:intersectsSegment(-8,7,8,7),0)
  r:returnToPool()
end)
test("rectangle outside-to-outside crossing returns 3 and endpoints",function()
  local r=rectangle()
  local a,b,n=point(),point(),point()
  eq(r:intersectsSegment(-9,0,9,0,a,b,n),3)
  close(a.x,-5);close(a.y,0)
  close(b.x,5);close(b.y,0)
  close(n.x,math.pi);close(n.y,0)
  r:returnToPool()
end)
test("rectangle outside-to-inside returns 1 and same intersection",function()
  local r=rectangle()
  local a,b,n=point(),point(),point()
  eq(r:intersectsSegment(-9,1,0,1,a,b,n),1)
  close(a.x,-5);close(a.y,1)
  close(b.x,-5);close(b.y,1)
  close(n.x,math.pi);close(n.y,2*math.pi)
  r:returnToPool()
end)
test("rectangle inside-to-outside returns 2 and original Y-from-X quirk",function()
  local r=rectangle()
  local a,b,n=point(),point(),point()
  eq(r:intersectsSegment(0,1,9,1,a,b,n),2)
  close(a.x,5);close(a.y,1)
  close(b.x,5);close(b.y,5) -- original upstream writes y=xB
  close(n.x,math.pi);close(n.y,0)
  r:returnToPool()
end)
test("rectangle static intersection has optional output points",function()
  eq(Rect.rectangleIntersectsSegment(-10,0,10,0,-2,-3,2,3),3)
  eq(Rect.rectangleIntersectsSegment(-1,0,1,0,-2,-3,2,3),-1)
  eq(Rect.rectangleIntersectsSegment(-10,5,10,5,-2,-3,2,3),0)
end)
test("rectangle Cohen-Sutherland boundary code uses original flags",function()
  eq(Rect._computeOutCode(-1,-1,0,0,10,10),5)
  eq(Rect._computeOutCode(11,11,0,0,10,10),10)
  eq(Rect._computeOutCode(0,0,0,0,10,10),0)
end)
test("rectangle _onClear returns pooled object and preserves type",function()
  local r=rectangle()
  r.color=0xffaa00
  local hash=r.hashCode
  r:returnToPool()
  local again=Base.borrowObject(Rect)
  assert(again==r and again.hashCode==hash)
  eq(again.color,0);eq(again.width,0);eq(again.height,0)
  eq(again.type,0)
  again:returnToPool()
end)

test("ellipse containsPoint follows original ellipse equation",function()
  local e=ellipse()
  assert(e:containsPoint(0,0))
  assert(e:containsPoint(5,0))
  assert(e:containsPoint(0,3))
  assert(not e:containsPoint(4,2.5))
  assert(not e:containsPoint(5.1,0))
  e:returnToPool()
end)
test("ellipse inside-to-inside segment returns -1",function()
  local e=ellipse()
  eq(e:intersectsSegment(-1,0,1,0),-1)
  e:returnToPool()
end)
test("ellipse crossing diameter yields two intersections and outward normals",function()
  local e=ellipse()
  local a,b,n=point(),point(),point()
  eq(e:intersectsSegment(-10,0,10,0,a,b,n),3)
  close(a.x,-5);close(a.y,0)
  close(b.x,5);close(b.y,0)
  close(math.abs(n.x),math.pi);close(n.y,0)
  e:returnToPool()
end)
test("ellipse outside-to-inside returns one crossing",function()
  local e=ellipse()
  local a,b=point(),point()
  eq(e:intersectsSegment(-10,0,0,0,a,b),1)
  close(a.x,-5);close(b.x,-5)
  close(a.y,0);close(b.y,0)
  e:returnToPool()
end)
test("ellipse inside-to-outside returns code 2 and one point",function()
  local e=ellipse()
  local a,b=point(),point()
  eq(e:intersectsSegment(0,0,10,0,a,b),2)
  close(a.x,5);close(b.x,5)
  close(a.y,0);close(b.y,0)
  e:returnToPool()
end)
test("ellipse missed chord returns 0",function()
  local e=ellipse()
  eq(e:intersectsSegment(-10,5,10,5),0)
  e:returnToPool()
end)
test("ellipse static method exposes original coordinate and radius parameters",function()
  local a,b=point(),point()
  eq(Ellipse.ellipseIntersectsSegment(-10,0,10,0,0,0,5,5,a,b),3)
  close(a.x,-5);close(b.x,5)
end)

test("polygon containsPoint follows ray crossing and bounding-box gate",function()
  local p=polygon()
  assert(p:containsPoint(5,5))
  assert(not p:containsPoint(-1,5))
  assert(not p:containsPoint(11,5))
  assert(not p:containsPoint(5,11))
  p:returnToPool()
end)
test("polygon line crossing returns 3 and extremes in original direction",function()
  local p=polygon()
  local a,b=point(),point()
  eq(p:intersectsSegment(-5,5,15,5,a,b),3)
  close(a.x,0);close(a.y,5)
  close(b.x,10);close(b.y,5)
  p:returnToPool()
end)
test("polygon opposite segment direction retains original nearest-to-A semantics",function()
  local p=polygon()
  local a,b=point(),point()
  eq(p:intersectsSegment(15,5,-5,5,a,b),3)
  close(a.x,10);close(b.x,0)
  p:returnToPool()
end)
test("polygon with pointB nil stops after first intersection as source",function()
  local p=polygon()
  local a=point()
  eq(p:intersectsSegment(-5,5,15,5,a,nil,nil),1)
  assert(math.abs(a.x)<1e-4 or math.abs(a.x-10)<1e-4)
  p:returnToPool()
end)
test("polygon miss rejected by rectangle pre-check",function()
  local p=polygon()
  eq(p:intersectsSegment(-5,20,15,20),0)
  p:returnToPool()
end)
test("polygon static intersection with no output points",function()
  local verts={0,0,10,0,10,10,0,10}
  eq(Polygon.polygonIntersectsSegment(-5,5,15,5,verts),1)
end)
test("polygon _onClear resets x,y,vertices and preserves array identity",function()
  local p=polygon()
  local verts=p.vertices
  p.color=0xffffff
  p:returnToPool()
  assert(p.vertices==verts and #p.vertices==0)
  eq(p.x,0);eq(p.y,0)
  eq(p.width,0);eq(p.height,0)
  eq(p.type,Core.BoundingBoxType.Polygon)
end)
test("bounding boxes are pooled by concrete type, not mixed together",function()
  local a=Base.borrowObject(Rect)
  local b=Base.borrowObject(Ellipse)
  local c=Base.borrowObject(Polygon)
  a:returnToPool();b:returnToPool();c:returnToPool()
  assert(Base.borrowObject(Rect)==a)
  assert(Base.borrowObject(Ellipse)==b)
  assert(Base.borrowObject(Polygon)==c)
end)

print(("Original BoundingBoxData.ts: %d passed, %d failed"):format(passed,failed))
if failed>0 then os.exit(1) end
