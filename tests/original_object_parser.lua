local passed,failed,assertions=0,0,0
local function eq(a,b)
  assertions=assertions+1
  assert(a==b,tostring(a).." ~= "..tostring(b))
end
local function near(a,b,epsilon)
  assertions=assertions+1
  assert(type(a)=="number" and type(b)=="number"
    and math.abs(a-b)<(epsilon or 1e-7),tostring(a).." ~= "..tostring(b))
end
local function check(name,fn)
  local ok,err=pcall(fn)
  if ok then passed=passed+1;print("ok original.object_parser "..name)
  else failed=failed+1;print("not ok original.object_parser "..name..": "..tostring(err)) end
end
local Tex={}
Tex.__index=Tex
setmetatable(Tex,{__index=AtlasModels.TextureData})
function Tex.new() return AtlasModels.TextureData.new(Tex) end
local Atlas={}
Atlas.__index=Atlas
setmetatable(Atlas,{__index=AtlasModels.TextureAtlasData})
function Atlas.new() return AtlasModels.TextureAtlasData.new(Atlas) end
function Atlas:createTexture() return Pool.borrowObject(Tex) end
local function freshAtlas() return Pool.borrowObject(Atlas) end
local function parser() return Parser.new() end
local function dummyArmature()
  local a={actions={},bones={},slots={}}
  function a:addAction(action)
    self.actions[#self.actions+1]=action
  end
  function a:getBone(name) return self.bones[name] end
  function a:getSlot(name) return self.slots[name] end
  return a
end
local function actionParser()
  local p=parser()
  p._armature=dummyArmature()
  return p
end

