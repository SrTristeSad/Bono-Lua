-- Conformance tests for:
-- geom/ColorTransform.ts and core/BaseObject.ts, original pinned DragonBonesJS.
package.path="./?.lua;./?/init.lua;"..package.path
local ColorTransform=require("dragonbones.original.geom.ColorTransform")
local BaseObject=require("dragonbones.original.core.BaseObject")
local passed,failed=0,0
local function test(label,fn)
  local ok,err=pcall(fn)
  if ok then passed=passed+1;print("ok original.core "..label)
  else failed=failed+1;print("not ok original.core "..label..": "..tostring(err)) end
end
local function fields(v,expected)
  for k,x in pairs(expected) do
    assert(v[k]==x, ("%s: expected %s, got %s"):format(k,tostring(x),tostring(v[k])))
  end
end
-- Lua form of a TS subclass with zero-argument constructor and _onClear().
local function class()
  local Class={}
  Class.__index=Class
  setmetatable(Class,{__index=BaseObject})
  function Class.new()
    local object=BaseObject.new(Class)
    object.clearCalls=0
    return object
  end
  function Class:_onClear()
    self.clearCalls=self.clearCalls+1
    self.contents=nil
  end
  return Class
end

test("ColorTransform constructor defaults exactly match original",function()
  fields(ColorTransform.new(),{
    alphaMultiplier=1,redMultiplier=1,greenMultiplier=1,blueMultiplier=1,
    alphaOffset=0,redOffset=0,greenOffset=0,blueOffset=0})
end)
test("ColorTransform constructor keeps zeroes and negative offsets",function()
  fields(ColorTransform.new(0,.2,2,-1,0,-3,10,4),{
    alphaMultiplier=0,redMultiplier=.2,greenMultiplier=2,blueMultiplier=-1,
    alphaOffset=0,redOffset=-3,greenOffset=10,blueOffset=4})
end)
test("ColorTransform copyFrom has void return and copies all fields",function()
  local source=ColorTransform.new(.1,.2,.3,.4,10,20,30,40)
  local target=ColorTransform.new()
  assert(target:copyFrom(source)==nil)
  fields(target,{alphaMultiplier=.1,redMultiplier=.2,greenMultiplier=.3,blueMultiplier=.4,
    alphaOffset=10,redOffset=20,greenOffset=30,blueOffset=40})
  source.redMultiplier=.9
  assert(target.redMultiplier==.2)
end)
test("ColorTransform identity is a void reset",function()
  local v=ColorTransform.new(0,0,0,0,1,2,3,4)
  assert(v:identity()==nil)
  fields(v,{alphaMultiplier=1,redMultiplier=1,greenMultiplier=1,blueMultiplier=1,
    alphaOffset=0,redOffset=0,greenOffset=0,blueOffset=0})
end)
test("BaseObject.toString throws like upstream",function()
  assert(not pcall(BaseObject.toString))
end)
test("BaseObject new object gets unique hashCode and initial _onClear",function()
  local Class=class()
  local first=BaseObject.borrowObject(Class)
  local second=BaseObject.borrowObject(Class)
  assert(first~=second)
  assert(second.hashCode==first.hashCode+1)
  assert(first.clearCalls==1 and second.clearCalls==1)
  assert(not first._isInPool and not second._isInPool)
  BaseObject.clearPool(Class)
end)
test("BaseObject returns to pool, LIFO, preserves hash and clears once per return",function()
  local Class=class()
  local a=BaseObject.borrowObject(Class)
  local b=BaseObject.borrowObject(Class)
  a.contents="a"
  b.contents="b"
  a:returnToPool()
  b:returnToPool()
  assert(a.clearCalls==2 and b.clearCalls==2)
  assert(a.contents==nil and b.contents==nil)
  local pulled=BaseObject.borrowObject(Class)
  assert(pulled==b and pulled.clearCalls==2 and not pulled._isInPool)
  local nextOne=BaseObject.borrowObject(Class)
  assert(nextOne==a and nextOne.hashCode==a.hashCode)
  BaseObject.clearPool(Class)
end)
test("BaseObject pools are segregated by constructor",function()
  local A=class()
  local B=class()
  local a=BaseObject.borrowObject(A)
  local b=BaseObject.borrowObject(B)
  a:returnToPool()
  b:returnToPool()
  assert(BaseObject.borrowObject(A)==a)
  assert(BaseObject.borrowObject(B)==b)
  BaseObject.clearPool(nil)
end)
test("BaseObject.setMaxCount limits pool size and trims surplus",function()
  local Class=class()
  BaseObject.clearPool(Class)
  BaseObject.setMaxCount(Class,2)
  local a=BaseObject.borrowObject(Class)
  local b=BaseObject.borrowObject(Class)
  local c=BaseObject.borrowObject(Class)
  a:returnToPool();b:returnToPool();c:returnToPool()
  local one=BaseObject.borrowObject(Class)
  local two=BaseObject.borrowObject(Class)
  assert(one==b and two==a,"third item discarded when pool is full")
  one:returnToPool();two:returnToPool()
  BaseObject.setMaxCount(Class,1)
  assert(BaseObject.borrowObject(Class)==one)
  BaseObject.clearPool(Class)
  BaseObject.setMaxCount(Class,3000)
end)
test("BaseObject negative/NaN maximum clamps to zero",function()
  local Class=class()
  local a=BaseObject.borrowObject(Class)
  BaseObject.setMaxCount(Class,-1)
  a:returnToPool()
  local b=BaseObject.borrowObject(Class)
  assert(b~=a)
  BaseObject.setMaxCount(Class,0/0)
  b:returnToPool()
  local c=BaseObject.borrowObject(Class)
  assert(c~=b)
  BaseObject.setMaxCount(Class,3000)
  BaseObject.clearPool(Class)
end)
test("BaseObject global setMaxCount revises existing overridden pools",function()
  local A=class()
  local B=class()
  BaseObject.setMaxCount(A,5)
  local a1=BaseObject.borrowObject(A)
  local a2=BaseObject.borrowObject(A)
  local b=BaseObject.borrowObject(B)
  a1:returnToPool();a2:returnToPool();b:returnToPool()
  BaseObject.setMaxCount(nil,1)
  assert(BaseObject.borrowObject(A)==a1)
  assert(BaseObject.borrowObject(B)==b)
  local newA=BaseObject.borrowObject(A)
  assert(newA~=a2)
  BaseObject.setMaxCount(nil,3000)
  BaseObject.clearPool(nil)
end)
test("BaseObject clearPool discards cached instances but not hash counter",function()
  local Class=class()
  local first=BaseObject.borrowObject(Class)
  first:returnToPool()
  BaseObject.clearPool(Class)
  local second=BaseObject.borrowObject(Class)
  assert(first~=second and second.hashCode>first.hashCode)
  BaseObject.clearPool(nil)
end)
test("BaseObject duplicate return remains one pool entry",function()
  local Class=class()
  local obj=BaseObject.borrowObject(Class)
  obj:returnToPool()
  obj:returnToPool()
  local first=BaseObject.borrowObject(Class)
  local second=BaseObject.borrowObject(Class)
  assert(first==obj and second~=obj)
  BaseObject.clearPool(Class)
end)
test("BaseObject rejected fractional Array.length resize matches JavaScript",function()
  local Class=class()
  local o=BaseObject.borrowObject(Class)
  o:returnToPool()
  assert(not pcall(BaseObject.setMaxCount,Class,.5))
  BaseObject.setMaxCount(Class,0)
  BaseObject.setMaxCount(Class,3000)
  BaseObject.clearPool(Class)
end)
print(("Original color/core port: %d passed, %d failed"):format(passed,failed))
if failed>0 then os.exit(1) end
