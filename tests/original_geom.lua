-- Conformance checks for DragonBonesJS geom ports, pinned source revision.
package.path="./?.lua;./?/init.lua;"..package.path
local Point=require("dragonbones.original.geom.Point")
local Rectangle=require("dragonbones.original.geom.Rectangle")
local Matrix=require("dragonbones.original.geom.Matrix")
local Transform=require("dragonbones.original.geom.Transform")
local passed,failed=0,0
local function test(name,body)
  local ok,err=pcall(body)
  if ok then passed=passed+1;print("ok original.geom "..name)
  else failed=failed+1;print("not ok original.geom "..name..": "..tostring(err)) end
end
local function eq(a,b,eps)
  assert(type(a)=="number" and type(b)=="number")
  assert(math.abs(a-b)<=(eps or 1e-9),tostring(a).." ~= "..tostring(b))
end
local function fields(actual,expected)
  for field,value in pairs(expected) do eq(actual[field],value) end
end

test("Point: create, copyFrom, clear and void return",function()
  local p=Point.new();fields(p,{x=0,y=0})
  assert(p:copyFrom(Point.new(7,-3))==nil)
  fields(p,{x=7,y=-3})
  assert(p:clear()==nil);fields(p,{x=0,y=0})
end)
test("Rectangle: create, copyFrom, clear and void return",function()
  local r=Rectangle.new(1,2,3,4)
  assert(r:copyFrom(Rectangle.new(-1,2,9,10))==nil)
  fields(r,{x=-1,y=2,width=9,height=10})
  assert(r:clear()==nil);fields(r,{x=0,y=0,width=0,height=0})
end)
test("Matrix: constructor, copy, copyFromArray zero-offset, identity",function()
  local m=Matrix.new();fields(m,{a=1,b=0,c=0,d=1,tx=0,ty=0})
  assert(m:copyFrom(Matrix.new(2,3,4,5,6,7))==m)
  assert(m:copyFromArray({99,98,8,9,10,11,12,13},2)==m)
  fields(m,{a=8,b=9,c=10,d=11,tx=12,ty=13})
  assert(m:identity()==m);fields(m,{a=1,b=0,c=0,d=1,tx=0,ty=0})
  assert(m:toString():find("[object dragonBones.Matrix]",1,true)==1)
end)
test("Matrix.concat: original multiplication order and zero-shear path",function()
  local m=Matrix.new(2,3,4,5,6,7)
  assert(m:concat(Matrix.new(11,13,17,19,23,29))==m)
  fields(m,{a=73,b=83,c=129,d=147,tx=208,ty=240})
  m=Matrix.new(2,0,0,3,5,7)
  m:concat(Matrix.new(4,0,0,6,1,2))
  fields(m,{a=8,b=0,c=0,d=18,tx=21,ty=44})
end)
test("Matrix.invert: general, diagonal and degenerate branches",function()
  local m=Matrix.new(2,1,3,4,5,6)
  assert(m:invert()==m)
  fields(m,{a=.8,b=-.2,c=-.6,d=.4,tx=-.4,ty=-1.4})
  m=Matrix.new(2,0,0,4,6,8);m:invert()
  fields(m,{a=.5,b=0,c=0,d=.25,tx=-3,ty=-2})
  m=Matrix.new(0,0,0,3,7,8);m:invert()
  -- Preserve original Matrix.ts peculiarity: d remains 3.
  fields(m,{a=0,b=0,c=0,d=3,tx=0,ty=0})
  m=Matrix.new(1,2,2,4,7,8);m:invert()
  fields(m,{a=1,b=0,c=0,d=1,tx=0,ty=0})
end)
test("Matrix.transformPoint: delta and void return",function()
  local m=Matrix.new(2,3,4,5,6,7)
  local p=Point.new()
  assert(m:transformPoint(1,2,p)==nil);fields(p,{x=16,y=20})
  m:transformPoint(1,2,p,true);fields(p,{x=10,y=13})
end)
test("Matrix.transformRectangle: floor, ceil and delta",function()
  local m=Matrix.new(0,1,-1,0,10,20)
  local r=Rectangle.new(2,3,4,5)
  assert(m:transformRectangle(r)==nil)
  fields(r,{x=2,y=22,width=5,height=4})
  r=Rectangle.new(2,3,4,5);m:transformRectangle(r,true)
  fields(r,{x=-8,y=2,width=5,height=4})
end)
test("Transform: identity, copyFrom, add, minus",function()
  local t=Transform.new(3,4,.2,.4,2,3)
  local saved=Transform.new()
  assert(saved:copyFrom(t)==saved)
  fields(saved,{x=3,y=4,skew=.2,rotation=.4,scaleX=2,scaleY=3})
  local other=Transform.new(1,-1,.1,.3,3,4)
  assert(saved:add(other)==saved)
  fields(saved,{x=4,y=3,skew=.3,rotation=.7,scaleX=6,scaleY=12})
  assert(saved:minus(other)==saved)
  fields(saved,{x=3,y=4,skew=.2,rotation=.4,scaleX=2,scaleY=3})
  assert(saved:identity()==saved)
  fields(saved,{x=0,y=0,skew=0,rotation=0,scaleX=1,scaleY=1})
end)
test("Transform.normalizeRadian: JavaScript signed remainder",function()
  eq(Transform.normalizeRadian(0),0)
  eq(Transform.normalizeRadian(2*math.pi),0)
  eq(Transform.normalizeRadian(3*math.pi),math.pi)
  eq(Transform.normalizeRadian(-math.pi),math.pi)
  eq(Transform.normalizeRadian(-3*math.pi),math.pi)
end)
test("Transform.toMatrix and fromMatrix: same decomposition",function()
  local t=Transform.new(8,12,0,math.pi/6,2,3)
  local m=Matrix.new();assert(t:toMatrix(m)==t)
  fields(m,{a=math.sqrt(3),b=1,c=-1.5,d=1.5*math.sqrt(3),tx=8,ty=12})
  local reconstructed=Transform.new()
  assert(reconstructed:fromMatrix(m)==reconstructed)
  fields(reconstructed,{x=8,y=12,skew=0,rotation=math.pi/6,scaleX=2,scaleY=3})
  assert(t:toString():find("[object dragonBones.Transform]",1,true)==1)
end)
test("Transform.fromMatrix: original negative scale correction",function()
  local m=Matrix.new(-1,0,0,1,4,5)
  local t=Transform.new();t:fromMatrix(m)
  fields(t,{x=4,y=5,scaleX=1,scaleY=1,rotation=-math.pi,skew=math.pi})
end)
print(("Original geometry port: %d passed, %d failed"):format(passed,failed))
if failed>0 then os.exit(1) end
