test("ArmatureData._onClear returns nested objects and preserves array/map identities",function()
  local a=Base.borrowObject(Armature)
  local bones,slots,skins,animations=a.bones,a.slots,a.skins,a.animations
  local sortedBones,sortedSlots=a.sortedBones,a.sortedSlots
  local actions,names,rect=a.actions,a.animationNames,a.aabb
  local b=bone("root");local s=slot("slot",b)
  local skin=Base.borrowObject(Skin);skin.name="default"
  local ik=Base.borrowObject(Con.IKConstraintData);ik.name="ik"
  local clip=animation("idle")
  a:addBone(b);a:addSlot(s);a:addSkin(skin);a:addConstraint(ik);a:addAnimation(clip)
  local action=Base.borrowObject(User.ActionData);a:addAction(action,false)
  local canvas=Base.borrowObject(Canvas)
  local userdata=Base.borrowObject(User.UserData)
  a.canvas=canvas;a.userData=userdata
  a.frameRate=60;a.scale=5;a.name="test";a.aabb.width=250
  a:returnToPool()
  assert(b._isInPool and s._isInPool and skin._isInPool and ik._isInPool)
  assert(action._isInPool and userdata._isInPool and canvas._isInPool)
  assert(clip.disposed)
  assert(a.bones==bones and a.slots==slots and a.skins==skins
    and a.animations==animations)
  assert(a.sortedBones==sortedBones and a.sortedSlots==sortedSlots)
  assert(a.animationNames==names and a.actions==actions and a.aabb==rect)
  assert(next(bones)==nil and next(slots)==nil and next(skins)==nil)
  assert(#sortedBones==0 and #sortedSlots==0 and #names==0 and #actions==0)
  eq(a.frameRate,0);eq(a.scale,1);eq(a.name,"");eq(a.aabb.width,0)
  assert(a.defaultSkin==nil and a.defaultAnimation==nil and a.canvas==nil)
end)

