local function eq(a,b) assert(a==b,tostring(a).." != "..tostring(b)) end
local function bone(name,parent)
  local v=Base.borrowObject(Bone);v.name=name;v.parent=parent;return v
end
local function slot(name,parent)
  local v=Base.borrowObject(Slot);v.name=name;v.parent=parent;return v
end
local function animation(name)
  -- Test-only dependency for original AnimationData.ts (not yet ported).
  local v={name=name,calls=0}
  function v:cacheFrames(rate) self.calls=self.calls+1;self.rate=rate end
  function v:returnToPool() self.disposed=true end
  return v
end
