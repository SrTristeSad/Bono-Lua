-- Conformance tests: DragonBonesJS WorldClock.ts at pinned commit.
package.path="./?.lua;./?/init.lua;"..package.path
local WorldClock=require("dragonbones.original.animation.WorldClock")
local passed,failed=0,0
local function test(name,fn)
  local success,err=pcall(fn)
  if success then
    passed=passed+1
    print("ok original.worldclock "..name)
  else
    failed=failed+1
    print("not ok original.worldclock "..name..": "..tostring(err))
  end
end
local function close(a,b)
  assert(math.abs(a-b)<1e-9,tostring(a).." != "..tostring(b))
end
local function actor()
  local result={clock=nil,steps={},callback=nil}
  function result:advanceTime(dt)
    self.steps[#self.steps+1]=dt
    if self.callback then self.callback(dt) end
  end
  return result
end
local function fakeTime(initial,fn)
  local old=WorldClock._now
  local current=initial
  WorldClock._now=function() return current end
  local success,err=pcall(fn,function(v) current=v end)
  WorldClock._now=old
  if not success then error(err) end
end

test("constructor initializes time, timeScale and system time",function()
  fakeTime(123.25,function()
    local w=WorldClock.new(7.5)
    assert(w.time==7.5 and w.timeScale==1)
    close(w._systemTime,123.25)
    assert(w.clock==nil and #w._animatebles==0)
    close(WorldClock.new().time,0)
  end)
end)
test("advanceTime uses explicit seconds and updates clock",function()
  fakeTime(10,function(set)
    local w=WorldClock.new()
    local x=actor()
    w:add(x)
    set(11)
    assert(w:advanceTime(.25)==nil)
    close(w.time,.25)
    close(w._systemTime,11)
    close(x.steps[1],.25)
    set(11.5)
    w:advanceTime(.75)
    close(w.time,1)
    close(x.steps[2],.75)
  end)
end)
test("passedTime negative samples elapsed platform time",function()
  fakeTime(20.25,function(set)
    local w=WorldClock.new(2)
    local x=actor()
    w:add(x)
    set(20.875)
    w:advanceTime(-1)
    close(w.time,2.625)
    close(x.steps[1],.625)
    set(21.0)
    w:advanceTime(-.1)
    close(w.time,2.75)
    close(x.steps[2],.125)
  end)
end)
test("NaN and zero do not advance but refresh _systemTime",function()
  fakeTime(2,function(set)
    local w=WorldClock.new()
    local x=actor()
    w:add(x)
    set(4)
    w:advanceTime(0/0)
    close(w.time,0)
    close(w._systemTime,4)
    set(6)
    w:advanceTime(0)
    close(w.time,0)
    close(w._systemTime,6)
    assert(#x.steps==0)
    set(6.5)
    w:advanceTime(-1)
    close(w.time,.5)
  end)
end)
test("timeScale positive, zero, negative follow original sign behavior",function()
  local w=WorldClock.new(1)
  local x=actor()
  w:add(x)
  w.timeScale=2
  w:advanceTime(.25)
  close(w.time,1.5)
  close(x.steps[1],.5)
  w.timeScale=0
  w:advanceTime(.25)
  close(w.time,1.5)
  assert(#x.steps==1)
  w.timeScale=-2
  w:advanceTime(.25)
  close(w.time,2)
  close(x.steps[2],-.5)
end)
test("add prevents duplicates, remove clears backref and compacts on advance",function()
  local w=WorldClock.new()
  local a,b=actor(),actor()
  assert(w:add(a)==nil)
  w:add(a);w:add(b)
  assert(a.clock==w and b.clock==w and #w._animatebles==2)
  assert(w:remove(a)==nil)
  assert(a.clock==nil and not w:contains(a))
  w:advanceTime(.25)
  assert(#w._animatebles==1 and w._animatebles[1]==b)
  assert(#a.steps==0 and #b.steps==1)
  w:remove(b)
  w:advanceTime(.25)
  assert(#w._animatebles==0)
end)
test("contains traces ancestor clocks and excludes itself",function()
  local grandparent=WorldClock.new()
  local parent=WorldClock.new()
  local child=WorldClock.new()
  local leaf=actor()
  parent.clock=grandparent
  child.clock=parent
  child:add(leaf)
  assert(grandparent:contains(parent))
  assert(grandparent:contains(child))
  assert(grandparent:contains(leaf))
  assert(not grandparent:contains(grandparent))
  assert(not child:contains(grandparent))
  grandparent:advanceTime(.125)
  close(leaf.steps[1],.125)
end)
test("WorldClock.clock setter moves nested clock from one parent to another",function()
  local a,b,c=WorldClock.new(),WorldClock.new(),WorldClock.new()
  c.clock=a
  assert(c.clock==a and a:contains(c))
  c.clock=b
  assert(c.clock==b and not a:contains(c) and b:contains(c))
  a:advanceTime(.1)
  assert(c.time==0)
  b:advanceTime(.2)
  close(c.time,.2)
  c.clock=nil
  assert(c.clock==nil and not b:contains(c))
  b:advanceTime(.2)
  close(c.time,.2)
end)
test("WorldClock.add nesting preserves same-parent setter recursion",function()
  local p=WorldClock.new()
  local c=WorldClock.new()
  p:add(c)
  p:add(c)
  assert(#p._animatebles==1 and c.clock==p)
  c.clock=p
  assert(#p._animatebles==1)
  p:advanceTime(.25)
  close(c.time,.25)
end)
test("remove during callback defers slot compaction but stops later item",function()
  local w=WorldClock.new()
  local first,middle,last=actor(),actor(),actor()
  first.callback=function() w:remove(middle) end
  w:add(first);w:add(middle);w:add(last)
  w:advanceTime(.1)
  assert(#middle.steps==0 and #last.steps==1)
  assert(#w._animatebles==2)
  assert(w._animatebles[1]==first and w._animatebles[2]==last)
  w:advanceTime(.1)
  assert(#last.steps==2)
end)
test("add during callback is not advanced until next call without holes",function()
  local w=WorldClock.new()
  local first,nextActor=actor(),actor()
  first.callback=function() w:add(nextActor) end
  w:add(first)
  w:advanceTime(.1)
  assert(#nextActor.steps==0)
  w:advanceTime(.2)
  assert(#nextActor.steps==1)
  close(nextActor.steps[1],.2)
end)
test("add during compaction retains new entry after current frame",function()
  local w=WorldClock.new()
  local removed=actor()
  local first,last,newActor=actor(),actor(),actor()
  first.callback=function() w:add(newActor) end
  w:add(removed);w:add(first);w:add(last)
  w:remove(removed)
  w:advanceTime(.1)
  assert(#newActor.steps==0)
  assert(#w._animatebles==3)
  assert(w._animatebles[1]==first and w._animatebles[2]==last and w._animatebles[3]==newActor)
  w:advanceTime(.2)
  assert(#newActor.steps==1)
end)
test("clear sets .clock null but leaves plain IAnimatable entries (upstream quirk)",function()
  local w=WorldClock.new()
  local a,b=actor(),actor()
  w:add(a);w:add(b)
  assert(w:clear()==nil)
  assert(a.clock==nil and b.clock==nil)
  assert(#w._animatebles==2)
  w:advanceTime(.2)
  assert(#a.steps==1 and #b.steps==1)
  assert(not w:contains(a))
end)
test("clear nested WorldClock delegates through its clock setter",function()
  local p=WorldClock.new()
  local child=WorldClock.new()
  p:add(child)
  p:clear()
  assert(child.clock==nil)
  p:advanceTime(.1)
  assert(child.time==0)
end)
test("remove and re-add before compaction preserves array null slot",function()
  local w=WorldClock.new()
  local a=actor()
  w:add(a)
  w:remove(a)
  w:add(a)
  assert(#w._animatebles==2 and a.clock==w)
  w:advanceTime(.1)
  assert(#a.steps==1 and #w._animatebles==1 and w._animatebles[1]==a)
end)

print(("Original WorldClock port: %d passed, %d failed"):format(passed,failed))
if failed>0 then os.exit(1) end
