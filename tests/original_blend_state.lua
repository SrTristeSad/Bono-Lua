-- Contract tests for the original BlendState class in AnimationState.ts.
-- DragonBonesJS 64b6c69ae35777c2404be68c9192e2c56906079e.
-- All runtime objects exercised are the real Lua ports; the animation state
-- input is only a plain data object with the original layer/_weightResult fields.
package.path = "./?.lua;./?/init.lua;" .. package.path
local BaseObject = require("dragonbones.original.core.BaseObject")
local BlendState = require("dragonbones.original.animation.BlendState")
local Animation = require("dragonbones.original.animation.Animation")
local Armature = require("dragonbones.original.armature.Armature")
local Model = require("dragonbones.original.model.ArmatureData")
local passed, failed, assertions = 0, 0, 0

local function eq(a,b)
  assertions = assertions + 1
  assert(a == b, tostring(a) .. " ~= " .. tostring(b))
end
local function near(a,b)
  assertions = assertions + 1
  assert(type(a)=="number" and type(b)=="number" and math.abs(a-b)<1e-10,
    tostring(a) .. " ~= " .. tostring(b))
end
local function test(name,fn)
  local ok,err=pcall(fn)
  if ok then
    passed=passed+1
    print("ok original.blend_state "..name)
  else
    failed=failed+1
    print("not ok original.blend_state "..name..": "..tostring(err))
  end
end
local function fresh()
  return BaseObject.borrowObject(BlendState)
end
local function state(layer,weight)
  return {layer=layer,_weightResult=weight}
end
local function put(blend,layer,weight)
  return blend:update(state(layer,weight))
end

test("source class name, constructor and BaseObject inheritance", function()
  local b=fresh()
  eq(BlendState.toString(),"[class dragonBones.BlendState]")
  eq(getmetatable(b),BlendState)
  eq(type(b.returnToPool),"function")
  eq(type(b.hashCode),"number")
  b:returnToPool()
end)
test("exact six static target category strings", function()
  eq(BlendState.BONE_TRANSFORM,"boneTransform")
  eq(BlendState.BONE_ALPHA,"boneAlpha")
  eq(BlendState.SURFACE,"surface")
  eq(BlendState.SLOT_DEFORM,"slotDeform")
  eq(BlendState.SLOT_ALPHA,"slotAlpha")
  eq(BlendState.SLOT_Z_INDEX,"slotZIndex")
end)
test("clear values match reset and target is nil",function()
  local b=fresh()
  eq(b.dirty,0);eq(b.layer,0)
  near(b.leftWeight,0);near(b.layerWeight,0)
  near(b.blendWeight,0)
  eq(b.target,nil)
end)
test("first update selects layer and initial weight",function()
  local b=fresh()
  eq(put(b,7,0.4),true)
  eq(b.dirty,1);eq(b.layer,7)
  near(b.leftWeight,1)
  near(b.blendWeight,0.4)
  near(b.layerWeight,0.4)
end)
test("first update returns true for exactly zero weight",function()
  local b=fresh()
  eq(put(b,2,0),true)
  eq(b.dirty,1);near(b.layerWeight,0)
  near(b.blendWeight,0);near(b.leftWeight,1)
end)
test("first update preserves weight above one without clamping",function()
  local b=fresh()
  eq(put(b,1,1.5),true)
  near(b.blendWeight,1.5)
  near(b.layerWeight,1.5)
  near(b.leftWeight,1)
end)
test("first update accepts negative weight unchanged",function()
  local b=fresh()
  eq(put(b,-4,-0.25),true)
  eq(b.layer,-4);near(b.blendWeight,-0.25)
  near(b.layerWeight,-0.25)
end)
test("same-layer update accumulates both weights",function()
  local b=fresh()
  put(b,3,0.2)
  eq(put(b,3,0.35),true)
  eq(b.dirty,2);eq(b.layer,3)
  near(b.leftWeight,1)
  near(b.blendWeight,0.35)
  near(b.layerWeight,0.55)
end)
test("same-layer update does not clamp layer total to 1",function()
  local b=fresh()
  put(b,3,0.7)
  eq(put(b,3,0.8),true)
  near(b.layerWeight,1.5)
  eq(b.dirty,2)
end)
test("switching layer deducts accumulated layer weight",function()
  local b=fresh()
  put(b,5,0.2)
  eq(put(b,4,0.5),true)
  eq(b.layer,4);eq(b.dirty,2)
  near(b.leftWeight,0.8)
  near(b.blendWeight,0.4)
  near(b.layerWeight,0.4)
end)
test("switching layers after multiple same-layer states",function()
  local b=fresh()
  put(b,10,0.25)
  put(b,10,0.15)
  eq(put(b,9,0.5),true)
  eq(b.dirty,3)
  near(b.leftWeight,0.6)
  near(b.blendWeight,0.3)
  near(b.layerWeight,0.3)
end)
test("new layer uses remaining weight, not original weight",function()
  local b=fresh()
  put(b,5,0.75)
  put(b,4,0.5)
  near(b.blendWeight,0.125)
  near(b.layerWeight,0.125)
end)
test("new layer weight can itself accumulate before next layer",function()
  local b=fresh()
  put(b,7,0.4)
  put(b,6,0.25)
  put(b,6,0.5)
  near(b.leftWeight,0.6)
  near(b.layerWeight,0.45)
  near(b.blendWeight,0.3)
end)
test("switching again uses remaining after previous layer",function()
  local b=fresh()
  put(b,5,0.4)
  put(b,4,0.5)
  eq(put(b,3,0.5),true)
  near(b.leftWeight,0.3)
  near(b.blendWeight,0.15)
end)
test("exhausted layer blocks the next layer and clears blendWeight",function()
  local b=fresh()
  put(b,5,1)
  eq(put(b,4,0.5),false)
  eq(b.dirty,2);eq(b.layer,4)
  near(b.leftWeight,0)
  near(b.blendWeight,0)
  near(b.layerWeight,1)
end)
test("exhausted layer blocks when accumulated weight greater than 1",function()
  local b=fresh()
  put(b,5,0.8)
  put(b,5,0.7)
  eq(put(b,4,0.5),false)
  near(b.layerWeight,1.5)
  near(b.leftWeight,0)
  eq(b.dirty,3)
end)
test("exhausted layer boundary uses >= comparison exactly",function()
  local b=fresh()
  put(b,10,0.5)
  eq(put(b,9,0.75),true)
  near(b.leftWeight,0.5)
  near(b.layerWeight,0.375)
  eq(put(b,8,1.0),true)
  near(b.leftWeight,0.125)
  near(b.blendWeight,0.125)
  eq(put(b,7,1.0),false)
  near(b.leftWeight,0)
end)
test("no remaining weight short-circuits without dirty increment",function()
  local b=fresh()
  put(b,3,1)
  put(b,2,0.2)
  local d=b.dirty
  eq(put(b,1,1),false)
  eq(b.dirty,d)
  eq(b.layer,2)
end)
test("no remaining weight keeps prior blend weight at zero",function()
  local b=fresh()
  put(b,3,1)
  put(b,2,0.2)
  eq(put(b,0,0.8),false)
  near(b.blendWeight,0)
end)
test("same layer with a zero weight still increments dirty",function()
  local b=fresh()
  put(b,3,0.25)
  eq(put(b,3,0),true)
  eq(b.dirty,2)
  near(b.layerWeight,0.25)
end)
test("switching after zero weight consumes no remaining capacity",function()
  local b=fresh()
  put(b,3,0)
  eq(put(b,2,0.3),true)
  near(b.leftWeight,1)
  near(b.layerWeight,0.3)
end)
test("negative first layer weight increases remaining budget",function()
  local b=fresh()
  put(b,3,-0.25)
  eq(put(b,2,0.5),true)
  near(b.leftWeight,1.25)
  near(b.blendWeight,0.625)
end)
test("empty reset restores numerical fields but retains target",function()
  local b=fresh()
  local target={}
  b.target=target
  put(b,10,0.75)
  eq(b:reset(),nil)
  eq(b.target,target)
  eq(b.dirty,0);eq(b.layer,0)
  near(b.leftWeight,0);near(b.layerWeight,0);near(b.blendWeight,0)
end)
test("update after reset restarts the blend from full weight",function()
  local b=fresh()
  put(b,2,1)
  put(b,1,0.2)
  b:reset()
  eq(put(b,8,0.4),true)
  eq(b.dirty,1);eq(b.layer,8)
  near(b.blendWeight,0.4);near(b.leftWeight,1)
end)
test("_onClear also drops the target, unlike reset",function()
  local b=fresh()
  b.target={}
  put(b,3,0.7)
  b:_onClear()
  eq(b.target,nil)
  eq(b.dirty,0);near(b.blendWeight,0)
end)
test("returnToPool and reborrow clear all original fields",function()
  local b=fresh()
  b.target={}
  put(b,5,0.7)
  b:returnToPool()
  local reused=fresh()
  eq(reused,b)
  eq(reused.target,nil);eq(reused.dirty,0)
  near(reused.leftWeight,0);near(reused.layerWeight,0)
  reused:returnToPool()
end)
test("Animation.getBlendState borrows real BlendState, caches same target",function()
  local anim=BaseObject.borrowObject(Animation)
  local target={}
  local b=anim:getBlendState(BlendState.BONE_TRANSFORM,"root",target)
  eq(getmetatable(b),BlendState)
  eq(b.target,target)
  eq(anim:getBlendState(BlendState.BONE_TRANSFORM,"root",{}),b)
  eq(b.target,target)
end)
test("Animation.getBlendState isolates same name across types",function()
  local anim=BaseObject.borrowObject(Animation)
  local target={}
  local b1=anim:getBlendState(BlendState.BONE_TRANSFORM,"root",target)
  local b2=anim:getBlendState(BlendState.BONE_ALPHA,"root",target)
  assert(b1~=b2)
  eq(b1.target,target);eq(b2.target,target)
end)
test("Animation.getBlendState isolates different targets in same type",function()
  local anim=BaseObject.borrowObject(Animation)
  local t1,t2={},{}
  local b1=anim:getBlendState(BlendState.BONE_TRANSFORM,"first",t1)
  local b2=anim:getBlendState(BlendState.BONE_TRANSFORM,"second",t2)
  assert(b1~=b2)
  eq(b1.target,t1);eq(b2.target,t2)
end)
test("Animation.advanceTime resets real BlendState before evaluating frames",function()
  local anim=BaseObject.borrowObject(Animation)
  local holder={inheritAnimation=true,_parent=nil,_cacheFrameIndex=7}
  function holder:getBones() return {} end
  function holder:getSlots() return {} end
  anim:init(holder)
  local b=anim:getBlendState(BlendState.BONE_TRANSFORM,"root",{})
  put(b,2,0.75)
  eq(b.dirty,1)
  anim:advanceTime(0.2)
  eq(b.dirty,0);near(b.blendWeight,0)
  eq(holder._cacheFrameIndex,-1)
end)
test("Animation.advanceTime can start a new blend after reset",function()
  local anim=BaseObject.borrowObject(Animation)
  local holder={inheritAnimation=true,_parent=nil,_cacheFrameIndex=-1}
  anim:init(holder)
  local b=anim:getBlendState(BlendState.SLOT_ALPHA,"head",{})
  put(b,8,1)
  anim:advanceTime(0.1)
  eq(put(b,4,0.25),true)
  near(b.leftWeight,1);eq(b.layer,4)
end)
test("Animation pool cleanup returns its real BlendState objects",function()
  local anim=BaseObject.borrowObject(Animation)
  local holder={inheritAnimation=true,_parent=nil}
  anim:init(holder)
  local b=anim:getBlendState(BlendState.BONE_ALPHA,"root",{})
  put(b,1,0.5)
  anim:returnToPool()
  eq(b._isInPool,true)
  eq(b.target,nil)
  local nextAnim=BaseObject.borrowObject(Animation)
  eq(nextAnim,anim)
  eq(next(nextAnim._blendStates),nil)
end)
test("real Armature.advanceTime drives real Animation and resets its blends",function()
  local armature=BaseObject.borrowObject(Armature)
  local model=BaseObject.borrowObject(Model.ArmatureData)
  model.name="test"
  model.parent={name="db",cachedFrames={}}
  local proxy={}
  function proxy:dbInit(owner) self.owner=owner end
  function proxy:dbUpdate() self.updated=(self.updated or 0)+1 end
  function proxy:dbClear() end
  armature:init(model,proxy,{}, {bufferObject=function() end})
  local blend=armature.animation:getBlendState(BlendState.SURFACE,"skin",{})
  put(blend,10,0.4)
  armature:advanceTime(1/60)
  eq(blend.dirty,0)
  eq(proxy.updated,1)
end)

print(("Original BlendState (AnimationState.ts): %d passed, %d failed, %d assertions"):format(passed,failed,assertions))
