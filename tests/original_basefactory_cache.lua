  doc.textureAtlas={{
    name="atlasOne",imagePath="first.png",
    SubTexture={{name="head",x=5,y=6,width=40,height=30}}
  },{
    name="atlasTwo",imagePath="second.png",
    SubTexture={{name="hand",x=2,y=3,width=4,height=5}}
