local passed,failed,checks=0,0,0
local function eq(a,b)
  checks=checks+1
  assert(a==b,tostring(a).." ~= "..tostring(b))
end
local function near(a,b)
  checks=checks+1
  assert(type(a)=="number" and type(b)=="number"
    and math.abs(a-b)<1e-7,tostring(a).." ~= "..tostring(b))
end
local function case(name,fn)
  local ok,err=pcall(fn)
  if ok then passed=passed+1;print("ok original.bone_slot_frames "..name)
  else failed=failed+1;print("not ok original.bone_slot_frames "..name..": "..tostring(err)) end
end
local function fixture(frameCount)
  local p=Parser.new()
  p._data=Pool.borrowObject(DB)
  local rig=Pool.borrowObject(Models.ArmatureData)
  rig.scale=1
  rig.frameRate=24
  p._armature=rig
  local anim=Pool.borrowObject(Animation.AnimationData)
  anim.frameCount=frameCount or 12
  anim.frameIntOffset=0
  anim.frameFloatOffset=0
  anim.frameOffset=0
  p._animation=anim
  return p,rig,anim
end
local function addBone(p,name,parent)
  local bone=Pool.borrowObject(Models.BoneData)
  bone.name=name
  bone.parent=parent
  p._armature:addBone(bone)
  return bone
end
local function addSlot(p,name,bone)
  local slot=Pool.borrowObject(Models.SlotData)
  slot.name=name
  slot.parent=bone
  p._armature:addSlot(slot)
  return slot
end
local function dump(p,name)
  local out={}
  for _,v in ipairs(p[name]) do out[#out+1]=v end
  return out
end

