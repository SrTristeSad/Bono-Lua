test("path constraints bind source modes, bones and actual display",function()
  local p,a=setup()
  local root=bone(p,a,{name="root"})
  local follower=bone(p,a,{name="follow"},root)
  local s=slot(p,a,{name="track",parent="root"})
  local skin=Pool.borrowObject(SkinData)
  local display=Pool.borrowObject(Displays.PathDisplayData)
  display.name="spline"
  skin:addDisplay("track",display)
  a:addSkin(skin)
  local c=p:_parsePathConstraint({
    name="path",target="track",targetDisplay="spline",
    bones={"follow","root"},positionMode="percent",spacingMode="fixed",
    rotateMode="chain",position=0.2,spacing=12,rotateOffset=5,
    rotateMix=0.4,translateMix=0.9
  })
  eq(getmetatable(c),Constraints.PathConstraintData)
  eq(c.name,"path");eq(c.type,Core.ConstraintType.Path)
  eq(c.pathSlot,s);eq(c.pathDisplayData,display);eq(c.target,root)
  eq(#c.bones,2);eq(c.bones[1],follower);eq(c.bones[2],root)
  near(c.position,0.2);near(c.spacing,12)
  near(c.rotateOffset,5);near(c.rotateMix,0.4);near(c.translateMix,0.9)
  eq(c.positionMode,Core.PositionMode.Percent)
  eq(c.spacingMode,Core.SpacingMode.Fixed)
  eq(c.rotateMode,Core.RotateMode.Chain)
end)
