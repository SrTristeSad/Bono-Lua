local pass,fail,assertions=0,0,0
local function eq(a,b)
  assertions=assertions+1
  assert(a==b,tostring(a).." ~= "..tostring(b))
end
local function near(a,b)
  assertions=assertions+1
  assert(type(a)=="number" and type(b)=="number" and math.abs(a-b)<1e-8,
    tostring(a).." ~= "..tostring(b))
end
local function test(name,fn)
  local ok,err=pcall(fn)
  if ok then pass=pass+1;print("ok original.object_parser_structure "..name)
  else fail=fail+1;print("not ok original.object_parser_structure "..name..": "..tostring(err)) end
end
local function setup(scale)
  local p=Parser.new()
  local a=Pool.borrowObject(Models.ArmatureData)
  a.name="test";a.scale=scale or 1
  p._armature=a
  return p,a
end
local function bone(p,a,raw,parent)
  local b=p:_parseBone(raw)
  b.parent=parent
  a:addBone(b)
  return b
end
local function slot(p,a,raw,z)
  local s=p:_parseSlot(raw,z or 0)
  a:addSlot(s)
  return s
end

