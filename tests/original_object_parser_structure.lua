test("actual bundled fixture parses bone-slot-skin hierarchy with model classes",function()
  local stream=assert(io.open("tests/fixtures/personagem-minimo.json","rb"))
  local raw=Json.decode(stream:read("*a"));stream:close()
  local arm=raw.armature[1]
  local p,a=setup(1)
  for _,boneRaw in ipairs(arm.bone) do
    local parent=a:getBone(boneRaw.parent or "")
    bone(p,a,boneRaw,parent)
  end
  for i,slotRaw in ipairs(arm.slot) do slot(p,a,slotRaw,i-1) end
  local skin=p:_parseSkin(arm.skin[1])
  a:addSkin(skin)
  eq(#a.sortedBones,3)
  eq(#a.sortedSlots,2)
  eq(a:getBone("forearm").parent,a:getBone("upperArm"))
  eq(a:getSlot("forearm").parent,a:getBone("forearm"))
  eq(#skin:getDisplays("upperArm"),2)
  eq(#skin:getDisplays("forearm"),1)
  eq(skin:getDisplay("upperArm","forearm").path,"forearm")
end)
